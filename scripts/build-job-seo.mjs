import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';
import {
  SITE, MIN_CITY_JOBS, MIN_STATE_JOBS, DISPLAY_LIMIT, applicationUrl, areaListings, eligiblePosting,
  getEmployerPostings, newestFirst, postingPath, readOpenCatalogue,
} from '../jobs/catalogue.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const CITIES = [['Raleigh', 'NC'], ['Chicago', 'IL'], ['New York', 'NY'],
  ['Austin', 'TX'], ['Seattle', 'WA'], ['San Francisco', 'CA'],
  ['Dallas', 'TX'], ['Houston', 'TX'], ['Charlotte', 'NC'], ['Atlanta', 'GA'], ['Boston', 'MA'],
  ['Washington', 'DC'], ['Jersey City', 'NJ'], ['Newark', 'NJ'], ['Arlington', 'VA'],
  ['Los Angeles', 'CA'], ['San Jose', 'CA'], ['Denver', 'CO'], ['Phoenix', 'AZ']];
const GENERATED = '<!-- Generated by scripts/build-job-seo.mjs -->';
const START = '<!-- BEGIN GENERATED JOB URLS -->';
const END = '<!-- END GENERATED JOB URLS -->';
const escape = value => String(value).replace(/[&<>"']/g, ch => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[ch]);
const cityPath = ({ role, city, state }) => '/jobs/' + role + '/' +
  city.toLowerCase().replaceAll(' ', '-') + '-' + state.toLowerCase() + '/';
const slug = name => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '');
const statePath = ({ role, stateName }) => '/jobs/' + role + '/' + slug(stateName) + '/';
const areaPath = target => target.city ? cityPath(target) : statePath(target);
const areaName = ({ city, state, stateName }) => city ? city + ', ' + state : stateName;
const directoryState = state => '/jobs/#state-' + state.toLowerCase();
const link = (path, label) => '<a href="' + escape(path) + '">' + escape(label) + '</a>';
const siteSearch = ({ title, city, state }) => '/results.html?' + new URLSearchParams({
  mode: 'quick', country: 'us', q: title, ...(city && { location: city + ', ' + state }),
});

function page({ path, title, description, body, noindex = false, live = false, trail = [['Home', '/'], ['Jobs', '/jobs/']] }) {
  const breadcrumbs = { '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: trail.map(([name, path], index) => ({
      '@type': 'ListItem', position: index + 1, name, item: SITE + path,
    })) };
  const schema = JSON.stringify(breadcrumbs).replaceAll('<', '\\u003c');
  const nav = '<nav aria-label="Breadcrumb">' + trail.map(([name, path], index) =>
    index === trail.length - 1 ? '<span aria-current="page">' + escape(name) + '</span>' : link(path, name)).join(' / ') + '</nav>';
  return '<!doctype html>\n' + GENERATED + '\n' +
    '<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">\n' +
    '<title>' + escape(title) + ' | Fortune Jobs AI</title>\n' +
    '<meta name="description" content="' + escape(description) + '">\n' +
    '<link rel="canonical" href="' + SITE + path + '">\n' +
    (noindex ? '<meta name="robots" content="noindex,follow">\n' : '') +
    '<link rel="icon" href="/favicon.ico?v=2" sizes="48x48"><link rel="icon" href="/favicon.svg?v=2" type="image/svg+xml"><link rel="apple-touch-icon" href="/apple-touch-icon.png?v=2"><link rel="stylesheet" href="/jobs/jobs.css">\n' +
    (live ? '<script src="/config.js"></script><script type="module" src="/jobs/live.mjs"></script>\n' : '') +
    '<script type="application/ld+json">' + schema + '</script>\n' +
    '</head><body><header><nav aria-label="Main navigation">' +
    '<a class="brand" href="/"><img src="/favicon.svg" alt="">Fortune Jobs AI</a>' +
    '<a href="/find-jobs.html">Find jobs</a></nav></header><main>\n' +
    nav + '\n' + body + '\n</main><footer><a href="/jobs/">Jobs by state and city</a> · ' +
    '<a href="/privacy.html">Privacy</a> · <a href="/terms.html">Terms</a></footer>' +
    "<script type=\"module\" src=\"https://static.cloudflareinsights.com/beacon.min.js\" data-cf-beacon='{\"token\":\"5e0de46ee5d94ffa87d7f7d4363a4b3d\"}'></script>" + '</body></html>\n';
}

export function renderCity(target, rows, details, date, related = []) {
  return renderArea(target, rows, details, date, related);
}

export function renderArea(target, rows, details, date, related = []) {
  const { role, city, state, stateName } = target;
  const place = areaName(target);
  const count = rows.length;
  const heading = count + ' ' + target.title + (count === 1 ? ' job in ' : ' jobs in ') + place;
  const path = areaPath(target);
  const visible = rows.slice(0, DISPLAY_LIMIT);
  const detailIds = rows.filter(job => details.has(String(job.id))).map(job => job.id);
  const items = visible.map(job => {
    const detail = details.has(String(job.id));
    return '<li><h2>' + escape(job.job_title) + '</h2><p>' + escape(job.company + ' · ' + job.location) +
      '</p>' + (job.posted_at ? '<p>Posted ' + escape(job.posted_at.slice(0, 10)) + '</p>' : '') + '<a rel="noopener noreferrer" href="' +
      escape(detail ? postingPath(job.id) : applicationUrl(job.apply_url)) + '">' +
      (detail ? 'View job details' : 'View original listing') + '</a>' +
      (job.source === 'adzuna' ? ' <small>Job source: Adzuna</small>' : '') + '</li>';
  }).join('\n');
  const status = count
    ? 'Showing ' + visible.length + ' of ' + count + ' open listings as of ' + date + '.'
    : 'No open listings in the ' + date + ' snapshot.';
  const relatedLinks = related.length ? '<h2>Related job searches</h2><ul>' + related.map(({ target }) =>
    '<li>' + link(areaPath(target), target.title + ' jobs in ' + areaName(target)) + '</li>').join('') + '</ul>' : '';
  const body = '<h1>' + escape(heading) + '</h1><p>' +
    (count ? 'Browse open ' + escape(target.title) + ' listings in ' + escape(place) + '. Use the original listing to confirm requirements and apply.' :
      'Our catalogue has no open ' + escape(target.title) + ' listings in ' + escape(place) + ' in this snapshot. Try a broader search.') +
    '</p><p>' + link(siteSearch(target), city ? 'Search this city in Quick Match' : 'Search this role nationwide') + '</p>' +
    '<section aria-label="Open listings" data-job-page="area" data-city="' + escape(city || '') +
    '" data-state="' + state + '" data-role="' + role + '" data-detail-ids="' + detailIds.join(',') +
    '"><p role="status">' + status + '</p><ul class="listings">' + items + '</ul></section>' + relatedLinks;
  const stateTrail = stateName ? [[stateName, directoryState(state)]] : [];
  return page({ path, title: heading, description: heading + ' as of ' + date + '. Browse listings and check the original posting before applying.',
    body, noindex: count < (city ? MIN_CITY_JOBS : MIN_STATE_JOBS), live: true,
    trail: [['Home', '/'], ['Jobs', '/jobs/'], ...stateTrail, [target.title + ' in ' + place, path]],
  });
}

function renderPosting(job) {
  return page({
    path: postingPath(job.id), title: job.job_title + ' at ' + job.company,
    description: 'View this ' + job.job_title + ' listing from ' + job.company + ' in ' + job.location + '.',
    body: '<article data-job-page="posting" data-id="' + job.id +
      '"><h1>' + escape(job.job_title) + '</h1><p role="status">Checking this listing…</p></article>' +
      '<p><a href="/find-jobs.html">Browse current jobs</a></p>',
    live: true,
    trail: [['Home', '/'], ['Jobs', '/jobs/'], [job.job_title, postingPath(job.id)]],
  });
}

export function addSitemapUrls(xml, paths) {
  const oldStart = xml.indexOf(START);
  if (oldStart >= 0) {
    const oldEnd = xml.indexOf(END, oldStart);
    if (oldEnd < 0) throw new Error('Generated sitemap section is incomplete');
    xml = xml.slice(0, oldStart) + xml.slice(oldEnd + END.length).replace(/^\r?\n/, '');
  }
  const close = xml.lastIndexOf('</urlset>');
  if (close < 0) throw new Error('Expected sitemap urlset');
  return xml.slice(0, close) + START + '\n' +
    paths.map(path => '  <url><loc>' + escape(SITE + path) + '</loc></url>\n').join('') +
    END + '\n' + xml.slice(close);
}

async function writePage(path, html) {
  const file = join(ROOT, path.slice(1), 'index.html');
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, html);
}

async function prunePages(directory, active, valid) {
  const folder = join(ROOT, 'jobs', directory);
  const entries = await readdir(folder, { withFileTypes: true }).catch(error => {
    if (error.code === 'ENOENT') return [];
    throw error;
  });
  for (const entry of entries) {
    if (!entry.isDirectory() || !valid(entry.name) || active.has(entry.name)) continue;
    const file = join(folder, entry.name, 'index.html');
    const html = await readFile(file, 'utf8').catch(error => {
      if (error.code === 'ENOENT') return '';
      throw error;
    });
    if (html.startsWith('<!doctype html>\n' + GENERATED)) await unlink(file);
  }
}

export function planPages(catalogue, roles, regions, now) {
  const groups = new Map();
  for (const job of [...catalogue].sort(newestFirst)) {
    const key = job.state_code + '/' + job.canonical_role;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(job);
  }
  const targetFor = (role, region, city) => ({
    role: role.id, title: role.name, state: region.code, stateName: region.name, city,
  });
  const rowsFor = target => areaListings(groups.get(target.state + '/' + target.role) || [], target, now);
  const statePages = regions.flatMap(region => roles.map(role => {
    const target = targetFor(role, region);
    return { target, rows: rowsFor(target) };
  })).filter(({ rows }) => rows.length >= MIN_STATE_JOBS);
  const cityPages = CITIES.filter(([, code]) => regions.some(region => region.code === code)).flatMap(([city, code]) => roles.map(role => {
    const target = targetFor(role, regions.find(region => region.code === code), city);
    return { target, rows: rowsFor(target) };
  }));
  return { statePages, cityPages };
}

async function build() {
  const window = {};
  runInNewContext(await readFile(join(ROOT, 'config.js'), 'utf8'), { window });
  const config = window.FJ_CONFIG;
  const now = Date.now();
  const date = new Date(now).toISOString().slice(0, 10);
  const [{ roles }, { regions }, catalogue, candidates] = await Promise.all([
    readFile(join(ROOT, 'config/job-roles.json'), 'utf8').then(JSON.parse),
    readFile(join(ROOT, 'config/us-regions.json'), 'utf8').then(JSON.parse),
    readOpenCatalogue(config),
    getEmployerPostings(config),
  ]);
  const postings = candidates.filter(job => eligiblePosting(job, now));
  const details = new Set(postings.map(job => String(job.id)));
  const { cityPages, statePages } = planPages(catalogue, roles, regions, now);
  const indexed = [...statePages, ...cityPages.filter(({ rows }) => rows.length >= MIN_CITY_JOBS)];
  for (const { target, rows } of [...statePages, ...cityPages]) {
    const related = indexed.filter(page => page.target !== target &&
      page.target.state === target.state && page.target.role === target.role);
    await writePage(areaPath(target), renderArea(target, rows, details, date, related));
  }
  for (const job of postings) await writePage(postingPath(job.id), renderPosting(job));
  await prunePages('posting', details, name => /^\d+$/.test(name));
  const stateSlugs = new Set(regions.map(region => slug(region.name)));
  for (const role of roles) {
    const active = new Set(statePages.filter(page => page.target.role === role.id).map(page => slug(page.target.stateName)));
    await prunePages(role.id, active, name => stateSlugs.has(name));
  }
  const sections = [...regions].sort((a, b) => a.name.localeCompare(b.name)).map(region => {
    const pages = indexed.filter(page => page.target.state === region.code);
    return '<section id="state-' + region.code.toLowerCase() + '"><h2>' + escape(region.name) + '</h2>' +
      (pages.length ? '<ul>' + pages.map(({ target, rows }) => '<li>' +
        link(areaPath(target), target.title + ' jobs in ' + areaName(target) + ' (' + rows.length + ')') +
        '</li>').join('') + '</ul>' : '<p>No indexed pages yet.</p>') + '</section>';
  }).join('\n');
  await writePage('/jobs/', page({
    path: '/jobs/', title: 'Browse jobs by state and city',
    description: 'Browse ' + indexed.length + ' job search pages by state, city and role.',
    body: '<h1>Browse jobs by state and city</h1><p>Explore current openings by location and role, or ' +
      link('/find-jobs.html', 'search all jobs') + '.</p>' + sections,
    noindex: indexed.length === 0,
  }));
  const sitemap = join(ROOT, 'sitemap.xml');
  const paths = [
    ...(indexed.length ? ['/jobs/'] : []),
    ...indexed.map(({ target }) => areaPath(target)),
    ...postings.map(job => postingPath(job.id)),
  ];
  await writeFile(sitemap, addSitemapUrls(await readFile(sitemap, 'utf8'), paths));
  console.log(statePages.length + ' state pages, ' + cityPages.length + ' city pages, ' +
    indexed.length + ' indexable area pages, ' + postings.length + ' eligible employer posting pages.');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) await build();
