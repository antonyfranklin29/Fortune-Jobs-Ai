import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const ROOT = new URL('../', import.meta.url);
const STATE = new URL('data/company-logo-resolution.json', ROOT);
const MAP = new URL('company-brand-map.js', ROOT);
const DAY = 86_400_000;

export function keyFor(name) {
  return String(name || '').trim().toLowerCase().replace(/\s+/g, ' ');
}

export function comparableName(name) {
  return keyFor(name).replace(/\s+(?:incorporated|inc|llc|ltd|limited|corp|corporation|co)\.?$/i, '')
    .replace(/[^a-z0-9]/g, '');
}

export function chooseCandidate(company, candidates) {
  const target = comparableName(company);
  if (!target || !Array.isArray(candidates)) return null;
  const exact = candidates.filter(item => comparableName(item?.name) === target &&
    typeof item.domain === 'string' && /^(?:[a-z0-9-]+\.)+[a-z]{2,}$/i.test(item.domain));
  const domains = [...new Set(exact.map(item => item.domain.toLowerCase()))];
  if (domains.length === 1) return domains[0];
  // Some well-known brands have many regional, alumni and merchandise domains.
  // Accept the main domain only when the provider ranks it first and its label
  // independently agrees with the entire company name.
  const first = candidates[0];
  if (target.length >= 5 && exact.includes(first)) {
    const domain = first.domain.toLowerCase();
    const label = domain.split('.')[0].replace(/[^a-z0-9]/g, '');
    if (label === target && domain.split('.').length === 2) return domain;
  }
  return null;
}

export function renderMap(state, publishableKey) {
  if (!/^[a-zA-Z0-9_-]{8,}$/.test(publishableKey)) throw new Error('Invalid publishable key');
  const map = Object.create(null);
  for (const [name, entry] of Object.entries(state)) {
    if (entry.status !== 'matched' || !/^(?:[a-z0-9-]+\.)+[a-z]{2,}$/i.test(entry.domain || '')) continue;
    map[name] = `https://img.logo.dev/${entry.domain.toLowerCase()}?token=${encodeURIComponent(publishableKey)}&size=96&format=png`;
  }
  return `/* Generated by scripts/sync-company-logos.mjs. The token is publishable, never the secret key. */\nwindow.FJ_COMPANY_BRANDS = Object.freeze(${JSON.stringify(Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b))), null, 2)});\n`;
}

async function catalogueCompanies(url, anonKey) {
  const names = new Set();
  for (let offset = 0; offset < 20_000; offset += 1000) {
    const query = new URLSearchParams({ select: 'company', closed_at: 'is.null', limit: '1000', offset: String(offset), order: 'company.asc' });
    const response = await fetch(`${url}/rest/v1/pre_scraped_jobs?${query}`, {
      headers: { apikey: anonKey, Authorization: `Bearer ${anonKey}` }
    });
    if (!response.ok) throw new Error(`Catalogue read failed: ${response.status}`);
    const rows = await response.json();
    if (!Array.isArray(rows)) throw new Error('Invalid catalogue response');
    for (const row of rows) if (keyFor(row.company)) names.add(keyFor(row.company));
    if (rows.length < 1000) return [...names].sort();
  }
  throw new Error('Catalogue exceeds 20,000 rows; raise the explicit safety bound');
}

async function main() {
  const url = process.env.FJ_SUPABASE_URL?.replace(/\/$/, '');
  const publicConfig = await readFile(new URL('config.js', ROOT), 'utf8');
  const anonKey = process.env.FJ_SUPABASE_ANON_KEY || publicConfig.match(/\bkey:\s*'([^']+)'/)?.[1];
  const secret = process.env.LOGO_DEV_SECRET_KEY;
  const publishable = process.env.LOGO_DEV_PUBLISHABLE_KEY;
  if (!url || !anonKey || !secret || !publishable) {
    throw new Error('Set FJ_SUPABASE_URL, LOGO_DEV_SECRET_KEY and LOGO_DEV_PUBLISHABLE_KEY in the environment. Never commit the secret key.');
  }
  if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/i.test(url)) throw new Error('Invalid Supabase URL');
  const companies = await catalogueCompanies(url, anonKey);
  const state = Object.create(null);
  try {
    for (const [name, entry] of Object.entries(JSON.parse(await readFile(STATE, 'utf8')))) state[name] = entry;
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  let queried = 0;
  for (const company of companies) {
    const previous = state[company];
    if (previous?.status === 'matched' ||
      (previous?.resolver_version === 2 && previous?.checked_at && Date.now() - Date.parse(previous.checked_at) < 30 * DAY)) continue;
    const request = new URL('https://api.logo.dev/v2/search');
    request.searchParams.set('q', company);
    request.searchParams.set('limit', '25');
    const response = await fetch(request, { headers: { Authorization: `Bearer ${secret}` } });
    if (!response.ok) throw new Error(`Logo search stopped at HTTP ${response.status}; saved progress remains local`);
    const body = await response.json();
    const domain = chooseCandidate(company, body.data);
    state[company] = {
      status: domain ? 'matched' : 'review', domain, checked_at: new Date().toISOString(), resolver_version: 2,
      ...(domain ? {} : { candidates: (Array.isArray(body.data) ? body.data : []).slice(0, 5).map(item => ({ name: item.name, domain: item.domain })) })
    };
    queried++;
    // Stay below the free plan's 500 search requests per minute.
    await new Promise(resolve => setTimeout(resolve, 150));
    if (queried % 20 === 0) {
      await mkdir(new URL('data/', ROOT), { recursive: true });
      await writeFile(STATE, `${JSON.stringify(state, null, 2)}\n`);
    }
  }
  await mkdir(new URL('data/', ROOT), { recursive: true });
  await writeFile(STATE, `${JSON.stringify(state, null, 2)}\n`);
  await writeFile(MAP, renderMap(state, publishable));
  const matched = companies.filter(company => state[company]?.status === 'matched').length;
  console.log(JSON.stringify({ companies: companies.length, matched, needs_review: companies.length - matched, queried }));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
