// Generates the role/region seed and SQL classifiers from config/*.json so the
// database and the edge worker apply one taxonomy. Postgres regex has no \b, so
// word boundaries become \y. Re-run after editing the config; the output is a
// migration file that is safe to apply repeatedly.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const roles = JSON.parse(fs.readFileSync(path.join(root, 'config/job-roles.json'), 'utf8'));
const regions = JSON.parse(fs.readFileSync(path.join(root, 'config/us-regions.json'), 'utf8'));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const pg = (re) => re.replace(/\\b/g, '\\y');
const anyOf = (pats) => pats.length ? '(' + pats.map((p) => `t ~* ${q(pg(p))}`).join(' or ') + ')' : 'false';

const roleRows = roles.roles.map((r, i) => `(${q(r.id)}, ${q(r.name)}, ${q(r.review)}, ${i})`).join(',\n  ');
const regionRows = regions.regions.map((r) => `(${q(r.code)}, ${q(r.name)}, ${r.separate ? 'true' : 'false'})`).join(',\n  ');
const classify = roles.roles.map((r) =>
  `  if ${anyOf(r.include)} and not ${anyOf(r.exclude)} then return ${q(r.id)}; end if;`).join('\n');

const sql = `-- GENERATED by scripts/build-ingest-sql.cjs from config/job-roles.json and
-- config/us-regions.json. Edit the config and regenerate; do not edit by hand.

create table if not exists public.ingest_roles (
  id text primary key, name text not null, review text not null, sort integer not null);
create table if not exists public.ingest_regions (
  code text primary key, name text not null, separate boolean not null default false);

insert into public.ingest_roles (id, name, review, sort) values
  ${roleRows}
on conflict (id) do update set name = excluded.name, review = excluded.review, sort = excluded.sort;

insert into public.ingest_regions (code, name, separate) values
  ${regionRows}
on conflict (code) do update set name = excluded.name, separate = excluded.separate;

alter table public.ingest_roles   enable row level security;
alter table public.ingest_regions enable row level security;
revoke all on public.ingest_roles, public.ingest_regions from public, anon, authenticated;
grant select on public.ingest_roles, public.ingest_regions to service_role;

-- Title -> canonical role, mirroring lib.mjs titleMatchesRole/classifyRole.
create or replace function public.ingest_classify_role(p_title text)
returns text language plpgsql immutable set search_path = public, pg_temp as $$
declare t text := coalesce(p_title, '');
begin
${classify}
  return null;
end $$;

-- Location string -> state code, mirroring lib.mjs stateFromEvidence's fallback.
-- Ambiguous input (e.g. "Washington, USA", "Carolina", "Remote") returns null.
create or replace function public.ingest_state_from_location(p_loc text)
returns text language plpgsql stable set search_path = public, pg_temp as $$
declare s text := btrim(coalesce(p_loc, '')); m text[]; parts text[]; tail text; v text;
begin
  if s ~* '(washington,?\\s*d\\.?\\s*c\\.?|district of columbia)' then return 'DC'; end if;
  m := regexp_match(s, ',\\s*([A-Z]{2})(\\s+\\d{5}(-\\d{4})?)?\\s*$');
  if m is not null and exists (select 1 from public.ingest_regions where code = m[1]) then return m[1]; end if;
  select array_agg(btrim(x)) into parts from unnest(string_to_array(s, ',')) x
   where btrim(x) <> '' and btrim(x) !~* '^(usa|us|united states)$';
  if coalesce(array_length(parts, 1), 0) >= 2 then
    tail := lower(parts[array_length(parts, 1)]);
    select code into v from public.ingest_regions where lower(name) = tail;
    return v;
  end if;
  -- State-level listing with no city; bare 'Washington' stays ambiguous.
  if coalesce(array_length(parts, 1), 0) = 1 and lower(parts[1]) <> 'washington' then
    select code into v from public.ingest_regions where lower(name) = lower(parts[1]);
    return v;
  end if;
  return null;
end $$;

revoke all on function public.ingest_classify_role(text) from public, anon, authenticated;
revoke all on function public.ingest_state_from_location(text) from public, anon, authenticated;
grant execute on function public.ingest_classify_role(text), public.ingest_state_from_location(text) to service_role;
`;
// The edge worker cannot read files outside its own folder once deployed, so it
// gets the same config embedded as a module.
fs.writeFileSync(path.join(root, 'supabase/functions/job-ingest/config.mjs'),
  '// GENERATED by scripts/build-ingest-sql.cjs from config/*.json. Do not edit.\n' +
  'export const ROLES = ' + JSON.stringify(roles) + ';\n' +
  'export const REGIONS = ' + JSON.stringify(regions) + ';\n');
const out = path.join(root, 'migrations/20261015_ingest_taxonomy.sql');
fs.writeFileSync(out, sql);
console.log('wrote', path.relative(root, out), `(${roles.roles.length} roles, ${regions.regions.length} regions)`);
