const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'supabase/functions/jobg8-ingest');
const src = fs.readFileSync(path.join(root, 'supabase/functions/job-ingest/lib.mjs'), 'utf8');
let out = '// GENERATED by scripts/build-jobg8-core.cjs. No URL canonicalisation.\n';
for (const n of ['compileRoles','titleMatchesRole','classifyRole']) {
 const i = src.indexOf('export function ' + n + '('), end = src.indexOf('\n}\n', i);
 out += src.slice(i, end + 2) + '\n';
}
fs.writeFileSync(path.join(dir, 'core.mjs'), out);
fs.copyFileSync(path.join(root,'supabase/functions/job-ingest/config.mjs'),path.join(dir,'config.mjs'));
