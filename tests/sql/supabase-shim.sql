-- Minimal stand-in for the parts of a Supabase project that the employer
-- migrations depend on, for a DISPOSABLE local PostgreSQL 16 database only.
-- Mirrors production as read on 2026-10-15: roles, auth.users, auth.uid(), and
-- pre_scraped_jobs before the ingest migrations, with its public read policy
-- and grants (anon/authenticated SELECT only; service_role full).
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
end $$;
grant usage on schema public to anon, authenticated, service_role;

create schema if not exists auth;
grant usage on schema auth to anon, authenticated, service_role;
create table if not exists auth.users (
  id uuid primary key default gen_random_uuid(),
  email text,
  email_confirmed_at timestamptz,
  raw_user_meta_data jsonb default '{}'::jsonb
);
-- Supabase reads the caller from the request JWT; tests set the same setting.
create or replace function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
grant execute on function auth.uid() to anon, authenticated, service_role;

create table if not exists public.pre_scraped_jobs (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  scraped_at timestamptz default now(),
  category text not null,
  job_title text, company text, location text, salary text,
  apply_url text unique,
  job_description text,
  source text default 'indeed',
  employment_type text, work_mode text,
  is_remote boolean default false,
  posted_at timestamptz,
  country text default 'us',
  search_text text
);
alter table public.pre_scraped_jobs enable row level security;
drop policy if exists "public can read pre-scraped jobs" on public.pre_scraped_jobs;
create policy "public can read pre-scraped jobs" on public.pre_scraped_jobs for select to anon, authenticated using (true);
revoke all on public.pre_scraped_jobs from anon, authenticated;
grant select on public.pre_scraped_jobs to anon, authenticated;
grant all on public.pre_scraped_jobs to service_role;
